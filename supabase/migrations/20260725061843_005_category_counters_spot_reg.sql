/*
# Migration 005 – Category-Based Registration Counters and Spot Registration

## Summary
Replaces the single spot-registration counter with four category-based
atomic counters, adds idempotency-key support to prevent duplicate
submissions, and provides admin functions for counter configuration and
dashboard totals.

## Changes to registration_counters
- `next_value` changed from NOT NULL to NULLABLE and the CHECK relaxed to
  allow NULL (NULL = counter not yet configured, used for exhibitor).
- Adds `start_value` (int, nullable): the configured starting number.
- Adds `last_used_value` (int, nullable): highest number actually assigned.
- Seeds four new counters:
    faculty_counter   → BPCON2026, start 150, next 150, padding 4
    delegate_counter  → BPCON2026, start 350, next 350, padding 4
    student_counter   → BPCON2026, start 850, next 850, padding 4
    (shared by Post Graduates AND Under Graduates)
    exhibitor_counter → BPCON2026, start NULL, next NULL (not configured)

## New Table: spot_registration_keys
Idempotency keys so a duplicate submit returns the existing attendee
instead of creating a second one.
- idempotency_key: unique text key generated by the frontend
- attendee_id: the attendee created on first submit
- RLS: admin SELECT only; INSERTs happen inside the SECURITY DEFINER
  create_spot_registration function (bypasses RLS).

## New/Replaced Functions
- create_spot_registration (new 8-param signature with p_idempotency_key):
  atomic lock on counter, skip existing imported numbers, crypto QR token,
  audit event, idempotency guard. Old 7-param version dropped.
- get_dashboard_totals(): aggregate counts, available to all active staff.
- get_counter_status(): admin-only counter overview.
- configure_counter(p_key, p_next, p_start): admin-only, validates the new
  next value is strictly greater than the highest existing registration
  number in that category's range.
- advance_counter_for_category(p_category): admin/registration, advances a
  counter beyond the highest imported number (Excel import support).

## RLS Changes
- rc_select: expanded to allow registration staff (in addition to admin)
  so the spot registration screen can check if exhibitor is configured.
- New policies on spot_registration_keys: admin SELECT only.

## Notes
1. The old 'spot_registration' counter row is left in place (no DELETE)
   but is no longer used by any function.
2. No real attendee data inserted.
*/

-- ──────────────── Relax constraints on registration_counters ───────────────

-- Drop the old CHECK that required next_value >= 1 AND NOT NULL
ALTER TABLE registration_counters DROP CONSTRAINT IF EXISTS registration_counters_next_value_check;

-- Make next_value nullable
ALTER TABLE registration_counters ALTER COLUMN next_value DROP NOT NULL;

-- Add a relaxed CHECK: either NULL (unconfigured) or >= 1
ALTER TABLE registration_counters
  ADD CONSTRAINT registration_counters_next_value_check
  CHECK (next_value IS NULL OR next_value >= 1);

-- Add new columns
ALTER TABLE registration_counters
  ADD COLUMN IF NOT EXISTS start_value int,
  ADD COLUMN IF NOT EXISTS last_used_value int;

-- Seed the four category counters (idempotent)
INSERT INTO registration_counters (counter_key, prefix, next_value, padding, start_value, last_used_value)
VALUES
  ('faculty_counter',   'BPCON2026', 150, 4, 150, NULL),
  ('delegate_counter',  'BPCON2026', 350, 4, 350, NULL),
  ('student_counter',   'BPCON2026', 850, 4, 850, NULL),
  ('exhibitor_counter', 'BPCON2026', NULL, 4, NULL, NULL)
ON CONFLICT (counter_key) DO NOTHING;

-- ──────────────────── spot_registration_keys table ─────────────────────────

CREATE TABLE IF NOT EXISTS spot_registration_keys (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  idempotency_key text NOT NULL UNIQUE,
  attendee_id     uuid NOT NULL REFERENCES attendees(id) ON DELETE CASCADE,
  created_by      uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE RESTRICT,
  created_at      timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE spot_registration_keys ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS spot_registration_keys_attendee_id_idx
  ON spot_registration_keys (attendee_id);

DROP POLICY IF EXISTS "srk_select" ON spot_registration_keys;
CREATE POLICY "srk_select"
ON spot_registration_keys FOR SELECT TO authenticated
USING (is_active_staff('admin'));

-- ─────────────── Update rc_select to include registration ──────────────────

DROP POLICY IF EXISTS "rc_select" ON registration_counters;
CREATE POLICY "rc_select"
ON registration_counters FOR SELECT TO authenticated
USING (
  is_active_staff('admin')
  OR is_active_staff('registration')
);

-- ─────────────── Replace create_spot_registration function ─────────────────

DROP FUNCTION IF EXISTS create_spot_registration(text,text,text,text,text,text,text);

CREATE OR REPLACE FUNCTION create_spot_registration(
  p_name            text,
  p_category        text,
  p_food_preference text,
  p_payment_status  text,
  p_phone_number    text DEFAULT NULL,
  p_email           text DEFAULT NULL,
  p_gender          text DEFAULT NULL,
  p_idempotency_key text DEFAULT NULL
)
RETURNS TABLE(
  registration_number text,
  qr_token            text,
  attendee_id         uuid
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_name        text;
  v_phone       text;
  v_email       text;
  v_counter_key text;
  v_counter     registration_counters%ROWTYPE;
  v_reg_no      text;
  v_exists      boolean;
  v_qr_token    text;
  v_attendee_id uuid;
  v_existing_id uuid;
BEGIN
  IF NOT is_active_staff('registration') AND NOT is_active_staff('admin') THEN
    RAISE EXCEPTION 'Permission denied: only registration or admin staff can create spot registrations';
  END IF;

  -- Idempotency: serialise on the key, return existing result if present
  IF p_idempotency_key IS NOT NULL THEN
    PERFORM pg_advisory_xact_lock(hashtext(p_idempotency_key));
    SELECT attendee_id INTO v_existing_id
    FROM spot_registration_keys
    WHERE idempotency_key = p_idempotency_key
    LIMIT 1;
    IF v_existing_id IS NOT NULL THEN
      RETURN QUERY SELECT a.registration_number, a.qr_token, a.id
      FROM attendees a WHERE a.id = v_existing_id;
      RETURN;
    END IF;
  END IF;

  v_name := btrim(p_name);
  IF v_name IS NULL OR v_name = '' THEN
    RAISE EXCEPTION 'Delegate name is required';
  END IF;
  IF length(v_name) > 200 THEN
    RAISE EXCEPTION 'Delegate name is too long (maximum 200 characters)';
  END IF;

  IF p_category NOT IN ('Delegates','Faculty','Post Graduates','Under Graduates','Exhibitors') THEN
    RAISE EXCEPTION 'Invalid category';
  END IF;

  IF p_food_preference NOT IN ('Vegetarian','Non-Vegetarian','Not Specified') THEN
    RAISE EXCEPTION 'Invalid food preference';
  END IF;

  IF p_payment_status NOT IN ('Paid','Pending','Complimentary') THEN
    RAISE EXCEPTION 'Invalid payment status';
  END IF;

  v_email := NULL;
  IF p_email IS NOT NULL AND btrim(p_email) != '' THEN
    v_email := lower(btrim(p_email));
    IF v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' THEN
      RAISE EXCEPTION 'Invalid email format';
    END IF;
  END IF;

  v_phone := NULL;
  IF p_phone_number IS NOT NULL AND btrim(p_phone_number) != '' THEN
    v_phone := btrim(p_phone_number);
    IF regexp_replace(v_phone, '\s', '', 'g') !~ '^(\+91)?[0-9]{10}$' THEN
      RAISE EXCEPTION 'Invalid phone number format';
    END IF;
  END IF;

  IF p_gender IS NOT NULL AND p_gender NOT IN ('Male','Female','Other','Prefer not to say') THEN
    RAISE EXCEPTION 'Invalid gender value';
  END IF;

  v_counter_key := CASE p_category
    WHEN 'Faculty'         THEN 'faculty_counter'
    WHEN 'Delegates'       THEN 'delegate_counter'
    WHEN 'Post Graduates'  THEN 'student_counter'
    WHEN 'Under Graduates' THEN 'student_counter'
    WHEN 'Exhibitors'      THEN 'exhibitor_counter'
  END;

  SELECT * INTO v_counter
  FROM registration_counters
  WHERE counter_key = v_counter_key
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Registration counter not found for category: %', p_category;
  END IF;

  IF v_counter.next_value IS NULL OR v_counter.start_value IS NULL THEN
    RAISE EXCEPTION 'Registration is not yet configured for category %. Please contact an administrator to set the starting registration number.', p_category;
  END IF;

  -- Find the next available number, skipping over any imported numbers
  LOOP
    v_reg_no := v_counter.prefix || '-' || lpad(v_counter.next_value::text, v_counter.padding, '0');
    SELECT EXISTS(SELECT 1 FROM attendees WHERE registration_number = v_reg_no) INTO v_exists;
    EXIT WHEN NOT v_exists;
    v_counter.next_value := v_counter.next_value + 1;
  END LOOP;

  v_qr_token := gen_random_uuid()::text;

  INSERT INTO attendees (
    registration_number, name, category, phone_number, email, gender,
    food_preference, payment_status, registration_type, qr_token,
    attendance_status, created_by
  )
  VALUES (
    v_reg_no, v_name, p_category, v_phone, v_email, p_gender,
    p_food_preference, p_payment_status, 'spot', v_qr_token,
    'not_checked_in', auth.uid()
  )
  RETURNING id INTO v_attendee_id;

  UPDATE registration_counters
  SET next_value      = v_counter.next_value + 1,
      last_used_value = v_counter.next_value,
      updated_at      = now()
  WHERE counter_key = v_counter_key;

  IF p_idempotency_key IS NOT NULL THEN
    INSERT INTO spot_registration_keys (idempotency_key, attendee_id, created_by)
    VALUES (p_idempotency_key, v_attendee_id, auth.uid());
  END IF;

  INSERT INTO audit_events (actor_id, action, target_type, target_id, details)
  VALUES (auth.uid(), 'spot_registration_created', 'attendee', v_attendee_id,
    jsonb_build_object(
      'registration_number', v_reg_no,
      'category', p_category,
      'name', v_name
    ));

  RETURN QUERY SELECT v_reg_no, v_qr_token, v_attendee_id;
END;
$$;

REVOKE ALL ON FUNCTION create_spot_registration(text,text,text,text,text,text,text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION create_spot_registration(text,text,text,text,text,text,text,text) TO authenticated;

-- ──────────────────── get_dashboard_totals function ────────────────────────

CREATE OR REPLACE FUNCTION get_dashboard_totals()
RETURNS TABLE(
  total_attendees  bigint,
  checked_in       bigint,
  CHECKED_OUT      bigint,
  not_checked_in   bigint,
  spot             bigint,
  pre_registered   bigint
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
BEGIN
  IF NOT is_active_staff() THEN
    RAISE EXCEPTION 'Permission denied: active staff required';
  END IF;

  RETURN QUERY
  SELECT
    COUNT(*)::bigint,
    COUNT(*) FILTER (WHERE attendance_status = 'checked_in')::bigint,
    COUNT(*) FILTER (WHERE attendance_status = 'checked_out')::bigint,
    COUNT(*) FILTER (WHERE attendance_status = 'not_checked_in')::bigint,
    COUNT(*) FILTER (WHERE registration_type = 'spot')::bigint,
    COUNT(*) FILTER (WHERE registration_type = 'pre_registered')::bigint
  FROM attendees;
END;
$$;

REVOKE ALL ON FUNCTION get_dashboard_totals() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION get_dashboard_totals() TO authenticated;

-- ──────────────────── get_counter_status function ──────────────────────────

CREATE OR REPLACE FUNCTION get_counter_status()
RETURNS TABLE(
  counter_key        text,
  display_name       text,
  prefix             text,
  start_value        int,
  next_value         int,
  last_used_value    int,
  highest_used_in_db int,
  configured         boolean
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
BEGIN
  IF NOT is_active_staff('admin') THEN
    RAISE EXCEPTION 'Permission denied: admin only';
  END IF;

  RETURN QUERY
  SELECT
    rc.counter_key,
    CASE rc.counter_key
      WHEN 'faculty_counter'   THEN 'Faculty'
      WHEN 'delegate_counter'  THEN 'Delegates'
      WHEN 'student_counter'   THEN 'Students (Post Graduates & Under Graduates)'
      WHEN 'exhibitor_counter' THEN 'Exhibitors'
    END,
    rc.prefix,
    rc.start_value,
    rc.next_value,
    rc.last_used_value,
    COALESCE((
      SELECT MAX(substring(a.registration_number FROM '([0-9]+)$')::int)
      FROM attendees a
      WHERE
        (rc.counter_key = 'faculty_counter'   AND a.category = 'Faculty')
        OR (rc.counter_key = 'delegate_counter'  AND a.category = 'Delegates')
        OR (rc.counter_key = 'student_counter'   AND a.category IN ('Post Graduates','Under Graduates'))
        OR (rc.counter_key = 'exhibitor_counter' AND a.category = 'Exhibitors')
    ), 0),
    rc.start_value IS NOT NULL
  FROM registration_counters rc
  WHERE rc.counter_key IN ('faculty_counter','delegate_counter','student_counter','exhibitor_counter')
  ORDER BY rc.counter_key;
END;
$$;

REVOKE ALL ON FUNCTION get_counter_status() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION get_counter_status() TO authenticated;

-- ──────────────────── configure_counter function ───────────────────────────

CREATE OR REPLACE FUNCTION configure_counter(
  p_counter_key     text,
  p_new_next_value  int,
  p_new_start_value int DEFAULT NULL
)
RETURNS TABLE(
  counter_key text,
  start_value int,
  next_value  int
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_highest_existing int;
BEGIN
  IF NOT is_active_staff('admin') THEN
    RAISE EXCEPTION 'Permission denied: admin only';
  END IF;

  IF p_counter_key NOT IN ('faculty_counter','delegate_counter','student_counter','exhibitor_counter') THEN
    RAISE EXCEPTION 'Invalid counter key: %', p_counter_key;
  END IF;

  IF p_new_next_value < 1 THEN
    RAISE EXCEPTION 'Next value must be a positive number';
  END IF;

  SELECT COALESCE(MAX(substring(a.registration_number FROM '([0-9]+)$')::int), 0)
  INTO v_highest_existing
  FROM attendees a
  WHERE
    (p_counter_key = 'faculty_counter'   AND a.category = 'Faculty')
    OR (p_counter_key = 'delegate_counter'  AND a.category = 'Delegates')
    OR (p_counter_key = 'student_counter'   AND a.category IN ('Post Graduates','Under Graduates'))
    OR (p_counter_key = 'exhibitor_counter' AND a.category = 'Exhibitors');

  IF p_new_next_value <= v_highest_existing THEN
    RAISE EXCEPTION 'Cannot set next number to % — registration number BPCON2026-% already exists. The next number must be greater than %.',
      p_new_next_value, lpad(v_highest_existing::text, 4, '0'), v_highest_existing;
  END IF;

  UPDATE registration_counters
  SET next_value  = p_new_next_value,
      start_value = COALESCE(p_new_start_value, start_value, p_new_next_value),
      updated_at  = now()
  WHERE counter_key = p_counter_key;

  INSERT INTO audit_events (actor_id, action, target_type, target_id, details)
  VALUES (auth.uid(), 'counter_configured', 'registration_counter', NULL,
    jsonb_build_object(
      'counter_key', p_counter_key,
      'new_next_value', p_new_next_value,
      'new_start_value', p_new_start_value
    ));

  RETURN QUERY
  SELECT p_counter_key, start_value, next_value
  FROM registration_counters
  WHERE counter_key = p_counter_key;
END;
$$;

REVOKE ALL ON FUNCTION configure_counter(text,int,int) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION configure_counter(text,int,int) TO authenticated;

-- ────────────── advance_counter_for_category function ──────────────────────

CREATE OR REPLACE FUNCTION advance_counter_for_category(p_category text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_counter_key  text;
  v_highest      int;
  v_current_next int;
BEGIN
  IF NOT is_active_staff('admin') AND NOT is_active_staff('registration') THEN
    RAISE EXCEPTION 'Permission denied: admin or registration staff required';
  END IF;

  v_counter_key := CASE p_category
    WHEN 'Faculty'         THEN 'faculty_counter'
    WHEN 'Delegates'       THEN 'delegate_counter'
    WHEN 'Post Graduates'  THEN 'student_counter'
    WHEN 'Under Graduates' THEN 'student_counter'
    WHEN 'Exhibitors'      THEN 'exhibitor_counter'
  END;

  IF v_counter_key IS NULL THEN
    RAISE EXCEPTION 'Invalid category: %', p_category;
  END IF;

  SELECT next_value INTO v_current_next
  FROM registration_counters
  WHERE counter_key = v_counter_key
  FOR UPDATE;

  SELECT COALESCE(MAX(substring(a.registration_number FROM '([0-9]+)$')::int), 0)
  INTO v_highest
  FROM attendees a
  WHERE
    (v_counter_key = 'faculty_counter'   AND a.category = 'Faculty')
    OR (v_counter_key = 'delegate_counter'  AND a.category = 'Delegates')
    OR (v_counter_key = 'student_counter'   AND a.category IN ('Post Graduates','Under Graduates'))
    OR (v_counter_key = 'exhibitor_counter' AND a.category = 'Exhibitors');

  IF v_highest >= COALESCE(v_current_next, 0) THEN
    UPDATE registration_counters
    SET next_value      = v_highest + 1,
        last_used_value = GREATEST(COALESCE(last_used_value, 0), v_highest),
        updated_at      = now()
    WHERE counter_key = v_counter_key;
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION advance_counter_for_category(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION advance_counter_for_category(text) TO authenticated;
