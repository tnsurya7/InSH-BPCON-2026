/*
# Migration 006 – Atomic Excel Import Function

## Summary
Adds import_attendees_batch(), a single SECURITY DEFINER RPC that inserts
an import_batches row, all valid attendees, and advances the relevant
category counters — all in one transaction. If anything fails, the whole
batch rolls back so no misleading completed batch is left behind.

## Function: import_attendees_batch(p_file_name, p_rows jsonb)
- Authorises admin or registration staff.
- Creates one import_batches row (file_name, row_count, imported_count).
- Inserts each valid attendee with registration_type='pre_registered',
  qr_token auto-generated by the DB default (gen_random_uuid()).
- Stamps import_batch_id and created_by on every attendee.
- After insert, calls advance_counter_for_category for each distinct
  category present in the import so future spot registrations cannot
  collide with imported numbers.
- Returns the batch id + imported count.
- If any attendee insert fails (e.g. duplicate registration_number),
  the entire transaction (batch + all attendees) is rolled back.

## RLS
No new policies. import_batches and attendees already have INSERT
policies for admin/registration. The function is SECURITY DEFINER so it
bypasses RLS, but still checks is_active_staff() for authorisation.

## Notes
1. Frontend validates rows BEFORE calling this function and only passes
   valid rows. The DB unique constraint on registration_number is the
   final safety net — a collision rolls back the whole batch.
2. qr_token is never set by the frontend; the DB column default
   gen_random_uuid()::text generates it (crypto-secure, no PII).
3. No real data inserted.
*/

CREATE OR REPLACE FUNCTION import_attendees_batch(
  p_file_name text,
  p_rows      jsonb
)
RETURNS TABLE(
  batch_id       uuid,
  imported_count int
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_batch_id     uuid;
  v_row          jsonb;
  v_attendee_id  uuid;
  v_count        int := 0;
  v_categories   text[];
  v_cat          text;
BEGIN
  IF NOT is_active_staff('admin') AND NOT is_active_staff('registration') THEN
    RAISE EXCEPTION 'Permission denied: only admin or registration staff can import';
  END IF;

  -- Create the batch record
  INSERT INTO import_batches (file_name, row_count, imported_count, rejected_count)
  VALUES (p_file_name, jsonb_array_length(p_rows), 0, 0)
  RETURNING id INTO v_batch_id;

  -- Insert each attendee
  FOR v_row IN SELECT * FROM jsonb_array_elements(p_rows)
  LOOP
    INSERT INTO attendees (
      registration_number, name, category, phone_number, email, gender,
      food_preference, payment_status, registration_type,
      import_batch_id, attendance_status, created_by
    )
    VALUES (
      v_row->>'registration_number',
      v_row->>'name',
      v_row->>'category',
      NULLIF(v_row->>'phone_number', ''),
      NULLIF(v_row->>'email', ''),
      NULLIF(v_row->>'gender', ''),
      v_row->>'food_preference',
      v_row->>'payment_status',
      'pre_registered',
      v_batch_id,
      'not_checked_in',
      auth.uid()
    )
    RETURNING id INTO v_attendee_id;
    v_count := v_count + 1;
  END LOOP;

  -- Update the batch with the actual imported count
  UPDATE import_batches
  SET imported_count = v_count,
      rejection_summary = jsonb_build_object('valid', v_count, 'rejected', 0)
  WHERE id = v_batch_id;

  -- Advance counters for each distinct category present
  SELECT DISTINCT (r->>'category') INTO v_categories
  FROM jsonb_array_elements(p_rows) r;

  FOREACH v_cat IN ARRAY v_categories
  LOOP
    PERFORM advance_counter_for_category(v_cat);
  END LOOP;

  -- Audit
  INSERT INTO audit_events (actor_id, action, target_type, target_id, details)
  VALUES (auth.uid(), 'excel_import_completed', 'import_batch', v_batch_id,
    jsonb_build_object('file_name', p_file_name, 'imported_count', v_count));

  RETURN QUERY SELECT v_batch_id, v_count;
END;
$$;

REVOKE ALL ON FUNCTION import_attendees_batch(text, jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION import_attendees_batch(text, jsonb) TO authenticated;
